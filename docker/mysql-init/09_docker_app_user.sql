-- ============================================================
-- 09_docker_app_user.sql  Docker 部署适配（不属于 server/db 的 8 个 T02 分片）
-- ============================================================
-- 08_sys_seed.sql 按最小权限创建的是 'wt_app'@'127.0.0.1'。
-- 容器化后应用从宿主机经端口映射访问，MySQL 看到的客户端地址是
-- Docker 网关（例如 172.x.0.1），匹配不到 127.0.0.1，登录会被拒绝。
-- 因此这里把账号重命名为 'wt_app'@'%'，原有逐表授权随 RENAME 一并保留。
--
-- 安全边界：
--   * 端口只发布在 127.0.0.1，仅本机可访问；
--   * 审计表 audit_log 仍是 SELECT, INSERT；
--   * 生产环境请把 '%' 收紧为具体来源网段，或改用 Docker 网络内直连。
-- ============================================================

RENAME USER 'wt_app'@'127.0.0.1' TO 'wt_app'@'%';

FLUSH PRIVILEGES;
